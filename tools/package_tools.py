#!/usr/bin/env python3
"""
Packaging and distribution tool for VisionTools.
Implements specifications VS-06 / TS-07 and resolves findings F03 / F05.

Single Source of Truth:
- Resolves dependency paths from build/resolved_dependencies.json (exported by CMake),
  falling back to tools/dependencies.yaml and environment variables.
- Derives module package contents strictly from the configured variant (GPU vs CPU).
- Stages to temporary sibling directory before publishing, preserving previous install tree on error (R10).
- GPU packages strictly require visiontools_infer.dll and backend DLLs.
- CPU packages never include GPU DLLs, visionrt.dl.yolo.yaml, or GPU module entries.
- Python example custom scripts are placed in optional examples/, not overwriting user custom tools.
- Package verification inspects manifest, module index, variant closure, indexed DLL existence (R06),
  CPU exclusion of GPU references (R07), and runtime DLL closure (R08).
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

def load_dependencies(build_dir: Path, project_root: Optional[Path] = None, strict: bool = False) -> Dict[str, Optional[Path]]:
    """
    Resolve dependency root paths.
    Priority:
      1. build_dir/resolved_dependencies.json (generated by CMake)
      2. tools/dependencies.yaml
      3. Environment variables / default paths
    """
    if project_root is None:
        project_root = Path(__file__).resolve().parent.parent

    resolved_file = build_dir / "resolved_dependencies.json"
    if strict and not resolved_file.exists():
        raise RuntimeError(f"Strict dependency resolution failed: missing required build metadata '{resolved_file}'")

    opencv_dir = None
    inferrt_root = None
    cuda_root = None
    tensorrt_root = None

    if resolved_file.exists():
        try:
            with open(resolved_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            if data.get("opencv_dir"):
                opencv_dir = Path(data["opencv_dir"])
            if data.get("inferrt_root"):
                inferrt_root = Path(data["inferrt_root"])
            if data.get("cuda_root"):
                cuda_root = Path(data["cuda_root"])
            if data.get("tensorrt_root"):
                tensorrt_root = Path(data["tensorrt_root"])
        except Exception as e:
            if strict:
                raise RuntimeError(f"Corrupt build metadata {resolved_file}: {e}")
            print(f"[WARN] Failed to read {resolved_file}: {e}")

    # Fallback to tools/dependencies.yaml only if NOT strict
    if not strict and not (opencv_dir and inferrt_root and cuda_root and tensorrt_root):
        deps_yaml_file = project_root / "tools" / "dependencies.yaml"
        yaml_defaults = {}
        if deps_yaml_file.exists():
            try:
                import yaml
                with open(deps_yaml_file, "r", encoding="utf-8") as f:
                    ydoc = yaml.safe_load(f)
                for item in ydoc.get("dependencies", []):
                    name = item.get("name")
                    default_path = item.get("default")
                    env_var = item.get("env")
                    if env_var and os.environ.get(env_var):
                        yaml_defaults[name] = Path(os.environ[env_var])
                    elif default_path:
                        yaml_defaults[name] = Path(default_path)
            except Exception:
                pass

        if not opencv_dir:
            opencv_dir = yaml_defaults.get("opencv", Path(os.environ.get("OpenCV_DIR", "D:/Software/dev/opencv-4.8.0/build/x64/vc16")))
        if not inferrt_root:
            inferrt_root = yaml_defaults.get("inferrt", Path(os.environ.get("INFERRT_ROOT", "F:/Projects/InferRT/InferRT-0.0.3")))
        if not cuda_root:
            cuda_root = yaml_defaults.get("cuda", Path(os.environ.get("CUDA_PATH", "C:/Program Files/NVIDIA GPU Computing Toolkit/CUDA/v11.8")))
        if not tensorrt_root:
            tensorrt_root = yaml_defaults.get("tensorrt", Path(os.environ.get("TRT_ROOT", "D:/Software/dev/TensorRT-10.16.1.11")))

    return {
        "opencv_dir": opencv_dir,
        "inferrt_root": inferrt_root,
        "cuda_root": cuda_root,
        "tensorrt_root": tensorrt_root
    }

def package_tools(
    build_dir: Path,
    install_dir: Path,
    config: str = "Release",
    infer_enabled: bool = True,
    strict: bool = False,
    project_root: Optional[Path] = None
):
    """
    Produce a clean, validated distribution tree.
    Uses temporary sibling staging to prevent destruction of existing release on build failure (R10).
    """
    build_dir = Path(build_dir).resolve()
    install_dir = Path(install_dir).resolve()
    if project_root is None:
        project_root = Path(__file__).resolve().parent.parent

    if install_dir == project_root or install_dir == Path.cwd().resolve() or install_dir in project_root.parents:
        raise RuntimeError(f"Refusing to package into project root or invalid install_dir: {install_dir}")

    target_variant = "gpu" if infer_enabled else "cpu"
    resolved_file = build_dir / "resolved_dependencies.json"
    if resolved_file.exists():
        try:
            with open(resolved_file, "r", encoding="utf-8") as f:
                deps_meta = json.load(f)
            if "generator_variant" in deps_meta and deps_meta["generator_variant"] != target_variant:
                raise RuntimeError(f"Build metadata variant mismatch: resolved_dependencies.json has '{deps_meta['generator_variant']}', packaging target is '{target_variant}'")
            if "build_infer" in deps_meta and bool(deps_meta["build_infer"]) != infer_enabled:
                raise RuntimeError(f"Build metadata build_infer mismatch: resolved_dependencies.json has build_infer={deps_meta['build_infer']}, packaging target is infer_enabled={infer_enabled}")
        except RuntimeError:
            raise
        except Exception as e:
            if strict:
                raise RuntimeError(f"Corrupt build metadata {resolved_file}: {e}")
    elif strict:
        raise RuntimeError(f"Strict packaging requires build metadata: {resolved_file}")

    # Use a staging directory to guarantee atomic delivery and preserve existing release on failure (R10)
    staging_dir = install_dir.parent / f".tmp_pkg_{install_dir.name}_{os.getpid()}"
    if staging_dir.exists():
        shutil.rmtree(staging_dir)
    staging_dir.mkdir(parents=True, exist_ok=True)

    try:
        bin_dir = staging_dir / "bin"
        bin_dir.mkdir(parents=True, exist_ok=True)

        manifest_files: List[Path] = []

        # 1. Check & Copy domain DLLs
        preprocess_candidates = [
            build_dir / "src" / "preprocess" / "visiontools_preprocess.dll",
            build_dir / "src" / "preprocess" / config / "visiontools_preprocess.dll",
            build_dir / "bin" / "visiontools_preprocess.dll",
        ]
        preprocess_dll = next((p for p in preprocess_candidates if p.exists()), None)
        if not preprocess_dll:
            raise RuntimeError(f"Could not find visiontools_preprocess.dll in {build_dir}")

        shutil.copy2(preprocess_dll, bin_dir / "visiontools_preprocess.dll")
        manifest_files.append(Path("bin") / "visiontools_preprocess.dll")

        if infer_enabled:
            infer_candidates = [
                build_dir / "src" / "infer" / "visiontools_infer.dll",
                build_dir / "src" / "infer" / config / "visiontools_infer.dll",
                build_dir / "bin" / "visiontools_infer.dll",
            ]
            infer_dll = next((p for p in infer_candidates if p.exists()), None)
            if not infer_dll:
                if strict:
                    raise RuntimeError(f"GPU packaging failed: could not find visiontools_infer.dll in {build_dir}")
                else:
                    print(f"[ERROR] Could not find visiontools_infer.dll in {build_dir}")
            else:
                shutil.copy2(infer_dll, bin_dir / "visiontools_infer.dll")
                manifest_files.append(Path("bin") / "visiontools_infer.dll")

        # 2. Copy builtin tool YAMLs (GPU tools excluded in CPU mode)
        src_builtin = project_root / "assets" / "tools" / "builtin"
        dst_builtin = staging_dir / "assets" / "tools" / "builtin"
        if src_builtin.exists():
            for root, dirs, files in os.walk(src_builtin):
                for file in files:
                    if not file.endswith((".yaml", ".yml")):
                        continue
                    # In CPU mode, omit visionrt.dl.yolo.yaml or any file in 深度学习
                    rel_from_builtin = Path(root).relative_to(src_builtin)
                    if not infer_enabled:
                        if "深度学习" in rel_from_builtin.parts or file == "visionrt.dl.yolo.yaml":
                            continue
                    src_path = Path(root) / file
                    target_folder = dst_builtin / rel_from_builtin
                    target_folder.mkdir(parents=True, exist_ok=True)
                    dest_path = target_folder / file
                    shutil.copy2(src_path, dest_path)
                    manifest_files.append(dest_path.relative_to(staging_dir))

        # 3. Copy Python custom tool examples into optional examples/ directory (VS-06)
        src_custom = project_root / "assets" / "tools" / "custom"
        dst_examples = staging_dir / "examples"
        if src_custom.exists():
            for root, dirs, files in os.walk(src_custom):
                for file in files:
                    src_path = Path(root) / file
                    rel_from_custom = Path(root).relative_to(src_custom)
                    target_folder = dst_examples / rel_from_custom
                    target_folder.mkdir(parents=True, exist_ok=True)
                    dest_path = target_folder / file
                    shutil.copy2(src_path, dest_path)
                    manifest_files.append(dest_path.relative_to(staging_dir))

        # 4. Handle module_index.json (strictly consume build index, no generator fallback, RS-02)
        target_variant = "gpu" if infer_enabled else "cpu"
        index_src = build_dir / "module_index.json"

        if not index_src.exists():
            raise RuntimeError(f"Missing required build index: {index_src}")

        try:
            with open(index_src, "r", encoding="utf-8") as f:
                idx_data = json.load(f)
        except Exception as e:
            raise RuntimeError(f"Corrupt build index {index_src}: {e}")

        if idx_data.get("variant") != target_variant:
            raise RuntimeError(f"Build index variant mismatch: expected '{target_variant}', got '{idx_data.get('variant')}'")

        tools_map = idx_data.get("tools")
        if not isinstance(tools_map, dict):
            raise RuntimeError(f"Invalid build index {index_src}: 'tools' must be a dictionary")

        if len(tools_map) == 0:
            raise RuntimeError(f"Invalid build index {index_src}: 'tools' dictionary is empty")

        shutil.copy2(index_src, staging_dir / "module_index.json")
        manifest_files.append(Path("module_index.json"))

        # 5. Copy runtime dependency DLLs
        deps = load_dependencies(build_dir, project_root, strict=strict)
        opencv_dir = deps["opencv_dir"]
        inferrt_root = deps["inferrt_root"]
        cuda_root = deps["cuda_root"]
        tensorrt_root = deps["tensorrt_root"]

        # OpenCV DLLs
        opencv_found = False
        if opencv_dir:
            opencv_bins = [
                opencv_dir / "bin",
                opencv_dir / ".." / "bin",
                opencv_dir.parent / "bin",
                opencv_dir / "x64" / "vc16" / "bin",
                opencv_dir
            ]
            for candidate in opencv_bins:
                if candidate.exists():
                    for dll in candidate.glob("*.dll"):
                        dest = bin_dir / dll.name
                        shutil.copy2(dll, dest)
                        manifest_files.append(Path("bin") / dll.name)
                        opencv_found = True
                    if opencv_found:
                        break
        if not opencv_found and strict:
            raise RuntimeError(f"No OpenCV DLLs found in {opencv_dir}")

        # GPU runtime dependencies
        if infer_enabled:
            # InferRT
            inferrt_found = False
            if inferrt_root:
                inferrt_bin = inferrt_root / "bin"
                if inferrt_bin.exists():
                    for dll in inferrt_bin.glob("*.dll"):
                        dest = bin_dir / dll.name
                        shutil.copy2(dll, dest)
                        manifest_files.append(Path("bin") / dll.name)
                        inferrt_found = True
            if not inferrt_found and strict:
                raise RuntimeError(f"No InferRT DLLs found in {inferrt_root}")

            # CUDA
            cuda_found = False
            if cuda_root:
                cuda_bin = cuda_root / "bin"
                if cuda_bin.exists():
                    for pat in ["cudart64_*.dll", "cublas64_*.dll", "cublasLt64_*.dll", "cudnn*.dll"]:
                        for dll in cuda_bin.glob(pat):
                            dest = bin_dir / dll.name
                            shutil.copy2(dll, dest)
                            manifest_files.append(Path("bin") / dll.name)
                            cuda_found = True
            if not cuda_found and strict:
                raise RuntimeError(f"No CUDA DLLs found in {cuda_root}")

            # TensorRT
            trt_found = False
            if tensorrt_root:
                trt_candidates = [tensorrt_root / "bin", tensorrt_root / "lib"]
                for tc in trt_candidates:
                    if tc.exists():
                        for pat in ["nvinfer*.dll", "nvonnxparser*.dll"]:
                            for dll in tc.glob(pat):
                                dest = bin_dir / dll.name
                                shutil.copy2(dll, dest)
                                manifest_files.append(Path("bin") / dll.name)
                                trt_found = True
                        if trt_found:
                            break
            if not trt_found and strict:
                raise RuntimeError(f"No TensorRT DLLs found in {tensorrt_root}")

        # 6. Write tools_manifest.txt
        manifest_path = staging_dir / "tools_manifest.txt"
        manifest_lines = [
            "# VisionTools distribution manifest",
            f"# variant: {target_variant}",
            ""
        ]
        for rel_path in sorted(set(manifest_files)):
            manifest_lines.append(str(rel_path).replace("\\", "/"))

        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write("\n".join(manifest_lines) + "\n")

        # 7. Pre-verify staging directory BEFORE touching install_dir (RS-04 / Q03)
        if not verify_package(staging_dir, is_gpu=infer_enabled):
            raise RuntimeError(f"Package verification failed on staging directory {staging_dir}")

        # 8. Atomically replace target install_dir with verified staging directory (RS-04 / Q03)
        backup_dir = None
        if install_dir.exists():
            backup_dir = install_dir.parent / f"{install_dir.name}.backup"
            if backup_dir.exists():
                shutil.rmtree(backup_dir, ignore_errors=True)
            install_dir.rename(backup_dir)

        try:
            staging_dir.rename(install_dir)
        except OSError:
            try:
                shutil.move(str(staging_dir), str(install_dir))
            except Exception as move_err:
                # Rollback from backup_dir
                if backup_dir and backup_dir.exists():
                    if install_dir.exists():
                        shutil.rmtree(install_dir, ignore_errors=True)
                    backup_dir.rename(install_dir)
                raise RuntimeError(f"Failed to replace install directory: {move_err}") from move_err

        # Successful replacement, clean up backup
        if backup_dir and backup_dir.exists():
            shutil.rmtree(backup_dir, ignore_errors=True)

        print(f"[package_tools] Successfully packaged {len(manifest_files)} items to {install_dir}")
        print(f"[package_tools] Manifest generated at {install_dir / 'tools_manifest.txt'}")

    except Exception:
        # Failure cleanup: ensure staging directory is removed, pre-existing install_dir is intact
        if staging_dir.exists():
            shutil.rmtree(staging_dir, ignore_errors=True)
        raise

def verify_package(install_dir: Path, is_gpu: bool = False) -> bool:
    """
    Verify packaging completeness, variant closure, indexed DLL existence, and runtime dependencies.
    """
    install_dir = Path(install_dir).resolve()
    manifest_path = install_dir / "tools_manifest.txt"
    if not manifest_path.exists():
        print(f"[ERROR] tools_manifest.txt not found in {install_dir}")
        return False

    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest_entries = [line.strip() for line in f if line.strip() and not line.startswith("#")]

    missing = []
    for rel_path in manifest_entries:
        p = Path(rel_path)
        if p.is_absolute() or ".." in p.parts:
            print(f"[ERROR] Manifest entry '{rel_path}' escapes package root")
            return False
        target = (install_dir / rel_path).resolve()
        try:
            if not target.is_relative_to(install_dir.resolve()):
                print(f"[ERROR] Manifest entry '{rel_path}' escapes package root")
                return False
        except AttributeError:
            pass
        if not target.exists():
            missing.append(rel_path)

    if missing:
        print(f"[ERROR] Package verification failed. Missing {len(missing)} manifest files: {missing}")
        return False

    index_path = install_dir / "module_index.json"
    if not index_path.exists():
        print(f"[ERROR] module_index.json not found in {install_dir}")
        return False

    try:
        with open(index_path, "r", encoding="utf-8") as f:
            idx = json.load(f)
    except Exception as e:
        print(f"[ERROR] Failed to parse module_index.json: {e}")
        return False

    expected_variant = "gpu" if is_gpu else "cpu"
    if idx.get("variant") != expected_variant:
        print(f"[ERROR] module_index.json variant mismatch: expected '{expected_variant}', got '{idx.get('variant')}'")
        return False

    bin_dir = install_dir / "bin"
    if not (bin_dir / "visiontools_preprocess.dll").exists():
        print("[ERROR] visiontools_preprocess.dll missing from package bin/")
        return False

    # Verify that every indexed C++ tool has its declared module_dll on disk (R06)
    # and CPU packages do not reference GPU DLLs (R07)
    tools_dict = idx.get("tools")
    if not isinstance(tools_dict, dict) or len(tools_dict) == 0:
        print("[ERROR] module_index.json 'tools' must be a non-empty dictionary")
        return False

    # Collect declared tool registries from packaged YAML files (if present)
    declared_registries = set()
    for yf in list(install_dir.glob("assets/tools/**/*.yaml")) + list(install_dir.glob("assets/tools/**/*.yml")):
        try:
            import yaml
            yd = yaml.safe_load(yf.read_text(encoding="utf-8")) or {}
            r = yd.get("entry", {}).get("registry_name") or yd.get("tool_id")
            if r:
                declared_registries.add(r)
        except Exception:
            pass

    for reg, tinfo in tools_dict.items():
        if not isinstance(tinfo, dict):
            print(f"[ERROR] Tool '{reg}' entry is not a dictionary: {tinfo}")
            return False

        known_kinds = {"cpp_function", "cpp_class", "python_function", "python_class"}
        kind = tinfo.get("kind")
        if not kind or kind not in known_kinds:
            print(f"[ERROR] Tool '{reg}' missing or invalid kind: '{kind}'")
            return False

        if declared_registries and reg not in declared_registries:
            print(f"[ERROR] Unknown tool registry '{reg}': not declared in packaged tool definitions")
            return False

        if kind.startswith("cpp"):
            mod_dll = tinfo.get("module_dll")
            if not mod_dll:
                print(f"[ERROR] C++ tool '{reg}' missing 'module_dll' in module_index.json")
                return False
            mod_path = Path(mod_dll)
            if mod_path.is_absolute() or ".." in mod_path.parts:
                print(f"[ERROR] Tool '{reg}' module_dll '{mod_dll}' escapes package root")
                return False
            dll_path = (install_dir / mod_dll).resolve()
            try:
                if not dll_path.is_relative_to(install_dir.resolve()):
                    print(f"[ERROR] Tool '{reg}' module_dll '{mod_dll}' escapes package root")
                    return False
            except AttributeError:
                pass
            # R06: Ensure declared DLL actually exists on disk
            if not dll_path.exists():
                print(f"[ERROR] Indexed module_dll '{mod_dll}' for tool '{reg}' does not exist: {dll_path}")
                return False
            # R07: CPU packages must never reference infer/GPU DLLs
            if not is_gpu:
                if "infer" in mod_path.name.lower():
                    print(f"[ERROR] CPU package index references GPU module DLL '{mod_dll}' for tool '{reg}'")
                    return False
        elif kind.startswith("python"):
            entry_dict = tinfo.get("entry", {})
            script = entry_dict.get("file") if isinstance(entry_dict, dict) else None
            if not script:
                script = tinfo.get("script")
            if not script:
                print(f"[ERROR] Python tool '{reg}' missing entry.file or script")
                return False
            script_path = Path(script)
            if script_path.is_absolute() or ".." in script_path.parts:
                print(f"[ERROR] Tool '{reg}' script '{script}' escapes package root")
                return False
            target_script = (install_dir / script).resolve()
            if not target_script.exists():
                candidates = [
                    install_dir / "examples" / script,
                    install_dir / "assets" / "tools" / "custom" / script,
                ]
                found_cand = next((c for c in candidates if c.exists()), None)
                if found_cand:
                    target_script = found_cand
                else:
                    print(f"[ERROR] Indexed Python script '{script}' for tool '{reg}' does not exist: {target_script}")
                    return False
        if not is_gpu:
            if "yolo" in reg.lower() or "infer" in reg.lower():
                print(f"[ERROR] CPU package index contains GPU tool '{reg}'")
                return False

    # Independent runtime DLL closure verification (R08)
    # 1. OpenCV runtime DLL presence (e.g. opencv_world480.dll)
    opencv_dlls = list(bin_dir.glob("opencv_*.dll"))
    if not opencv_dlls:
        print("[ERROR] Package verification failed: no OpenCV runtime DLL (opencv_*.dll) found in bin/")
        return False

    if is_gpu:
        if not (bin_dir / "visiontools_infer.dll").exists():
            print("[ERROR] GPU package verification failed: visiontools_infer.dll is missing")
            return False
        if not list(install_dir.rglob("visionrt.dl.yolo.yaml")):
            print("[ERROR] GPU package verification failed: visionrt.dl.yolo.yaml is missing")
            return False
        # InferRT runtime DLL
        inferrt_dlls = list(bin_dir.glob("inferrt*.dll"))
        if not inferrt_dlls:
            print("[ERROR] GPU package verification failed: no InferRT runtime DLL (inferrt*.dll) found in bin/")
            return False
        # CUDA runtime DLL
        cuda_dlls = list(bin_dir.glob("cudart64_*.dll"))
        if not cuda_dlls:
            print("[ERROR] GPU package verification failed: no CUDA runtime DLL (cudart64_*.dll) found in bin/")
            return False
        # TensorRT core runtime DLL (cannot be satisfied solely by plugin/dispatch/lean libraries)
        core_trt_dlls = [
            dll for dll in bin_dir.glob("nvinfer*.dll")
            if not (
                dll.name.startswith("nvinfer_plugin") or
                dll.name.startswith("nvinfer_dispatch") or
                dll.name.startswith("nvinfer_lean")
            )
        ]
        if not core_trt_dlls:
            print("[ERROR] GPU package verification failed: no TensorRT core runtime DLL (nvinfer*.dll excluding plugins) found in bin/")
            return False
    else:
        # Strict CPU mode check: no GPU DLL or YAML
        if (bin_dir / "visiontools_infer.dll").exists():
            print("[ERROR] CPU package verification failed: visiontools_infer.dll found in CPU package")
            return False
        if list(install_dir.rglob("visionrt.dl.yolo.yaml")):
            print("[ERROR] CPU package verification failed: visionrt.dl.yolo.yaml found in CPU package")
            return False
        if list(bin_dir.glob("inferrt*.dll")):
            print("[ERROR] CPU package verification failed: inferrt*.dll found in CPU package")
            return False
        if list(bin_dir.glob("cudart64_*.dll")):
            print("[ERROR] CPU package verification failed: cudart64_*.dll found in CPU package")
            return False
        if list(bin_dir.glob("nvinfer*.dll")):
            print("[ERROR] CPU package verification failed: nvinfer*.dll found in CPU package")
            return False

    print(f"[SUCCESS] Package verification passed ({len(manifest_entries)} files verified, variant={expected_variant}).")
    return True

def main():
    parser = argparse.ArgumentParser(description="Package VisionTools distribution tree")
    parser.add_argument("--build-dir", default="build", help="Build directory")
    parser.add_argument("--install-dir", default="dist/VisionTools", help="Target installation directory")
    parser.add_argument("--config", default="Release", help="Build configuration (Release/Debug)")
    parser.add_argument("--no-infer", action="store_true", help="Package CPU-only tools")
    parser.add_argument("--verify", action="store_true", help="Verify existing package")
    parser.add_argument("--strict", action="store_true", default=True, help="Strictly fail if required DLLs are missing")
    args = parser.parse_args()

    install_dir = Path(args.install_dir)
    is_gpu = not args.no_infer

    if args.verify:
        ok = verify_package(install_dir, is_gpu=is_gpu)
        sys.exit(0 if ok else 1)

    try:
        package_tools(
            Path(args.build_dir),
            install_dir,
            config=args.config,
            infer_enabled=is_gpu,
            strict=args.strict
        )
    except Exception as e:
        print(f"[ERROR] Packaging failed: {e}")
        sys.exit(1)

    ok = verify_package(install_dir, is_gpu=is_gpu)
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main()
